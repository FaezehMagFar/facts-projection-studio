    def all_location_rows(self) -> list[str]:
        path = Path(self.locations.text().strip())
        if not path.is_file(): return []
        rows = []
        for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
            line = raw.strip()
            if not line or line.startswith("#"): continue
            parts = line.split("\t")
            if len(parts) != 4: continue
            try: int(parts[1]); float(parts[2]); float(parts[3])
            except ValueError: continue
            rows.append("\t".join(parts))
        return rows

    def valid_location_rows(self) -> list[str]:
        rows = self.all_location_rows()
        if self.selected_station_ids is None:
            return rows
        return [row for row in rows if row.split("\t")[1] in self.selected_station_ids]

    def select_locations(self) -> None:
        rows = self.all_location_rows()
        if not rows:
            QMessageBox.warning(self, "No valid locations", "Choose a valid location-list file first.")
            return
        selected_ids = (self.selected_station_ids if self.selected_station_ids is not None
                        else {row.split("\t")[1] for row in rows})
        dialog = QDialog(self)
        dialog.setWindowTitle("Select FACTS locations")
        dialog.resize(760, 620)
        layout = QVBoxLayout(dialog)
        instructions = QLabel(
            "Click any row to select or unselect it. Blue rows will be included in the FACTS run.")
        instructions.setWordWrap(True)
        layout.addWidget(instructions)
        table = QTableWidget(len(rows), 4)
        table.setObjectName("locationSelector")
        table.setHorizontalHeaderLabels(("Location", "Station ID", "Latitude", "Longitude"))
        table.verticalHeader().setVisible(False)
        table.setSelectionBehavior(QTableWidget.SelectionBehavior.SelectRows)
        table.setSelectionMode(QTableWidget.SelectionMode.MultiSelection)
        table.setEditTriggers(QTableWidget.EditTrigger.NoEditTriggers)
        table.horizontalHeader().setSectionResizeMode(0, QHeaderView.ResizeMode.Stretch)
        for index, row in enumerate(rows):
            name, station, latitude, longitude = row.split("\t")
            name_item = QTableWidgetItem(name.replace("_", " "))
            table.setItem(index, 0, name_item)
            table.setItem(index, 1, QTableWidgetItem(station))
            table.setItem(index, 2, QTableWidgetItem(latitude))
            table.setItem(index, 3, QTableWidgetItem(longitude))
            if station in selected_ids:
                table.selectionModel().select(
                    table.model().index(index, 0),
                    QItemSelectionModel.SelectionFlag.Select
                    | QItemSelectionModel.SelectionFlag.Rows)
        layout.addWidget(table)
        actions = QHBoxLayout()
        select_all = QPushButton("Select all")
        select_all.clicked.connect(table.selectAll)
        clear_all = QPushButton("Clear all")
        clear_all.clicked.connect(table.clearSelection)
        actions.addWidget(select_all); actions.addWidget(clear_all); actions.addStretch(1)
        layout.addLayout(actions)
        buttons = QDialogButtonBox(
            QDialogButtonBox.StandardButton.Cancel | QDialogButtonBox.StandardButton.Ok)
        buttons.accepted.connect(dialog.accept); buttons.rejected.connect(dialog.reject)
        layout.addWidget(buttons)
        if dialog.exec() != QDialog.DialogCode.Accepted:
            return
        self.selected_station_ids = {
            table.item(index.row(), 1).text()
            for index in table.selectionModel().selectedRows(0)
        }
        self.update_location_count()

