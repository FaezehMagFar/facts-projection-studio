    def set_busy(self, busy: bool, message: str) -> None:
        self.status.setText(message)
        for button in (self.check_button, self.install_button, self.run_button,
                       self.generate_button):
            button.setEnabled(not busy)
        self.cancel_setup.setEnabled(busy)
        self.cancel_run.setEnabled(busy)

    def append_setup(self, text: str) -> None:
        self.setup_log.moveCursor(self.setup_log.textCursor().MoveOperation.End)
        self.setup_log.insertPlainText(text)
        self.setup_log.ensureCursorVisible()

    def append_run(self, text: str) -> None:
        self.run_log.moveCursor(self.run_log.textCursor().MoveOperation.End)
        self.run_log.insertPlainText(text)
        match = re.search(r"tasks\s+(\d+)/(\d+)", text)
        if match:
            done, total = map(int, match.groups())
            self.progress.setValue(min(99, round(done * 100 / max(total, 1))))
        self.run_log.ensureCursorVisible()

    def start_task(self, task: Callable, output: Callable[[str], None], label: str) -> None:
        if self.worker is not None and self.worker.isRunning():
            QMessageBox.information(self, "FACTS is busy", "Wait for the active operation to finish.")
            return
        self.set_busy(True, label)
        self.worker = TaskWorker(task)
        self.worker.output.connect(output)
        self.worker.completed.connect(self.task_finished)
        self.worker.start()

    def task_finished(self, code: int, message: str) -> None:
        self.set_busy(False, message if code == 0 else "Failed: " + message)
        if code == 0:
            self.progress.setValue(100 if self.tabs.currentIndex() == 1 else self.progress.value())
        self.worker = None
        self.check_system()

    def cancel_task(self) -> None:
        if self.worker is not None:
            self.worker.cancel()
            self.status.setText("Cancelling…")

    def status_rows(self) -> list[tuple[str, bool, str]]:
        docker_ok, docker_detail = docker_ready()
        ubuntu_ok = ubuntu_available()
        tools_ok = False
        home = ""
        if ubuntu_ok:
            code, detail = run_capture(["wsl.exe", "-d", "Ubuntu", "--", "bash", "-lc",
                                        "command -v python3 && python3 -c 'import tkinter' && command -v git && command -v wget"], 30)
            tools_ok = code == 0
            try: home = wsl_home()
            except RuntimeError: pass
        repo = f"{home}/facts_ssisls/facts" if home else "~/facts_ssisls/facts"
        repo_ok = ubuntu_ok and run_capture(
            ["wsl.exe", "-d", "Ubuntu", "--", "test", "-d", repo + "/.git"], 15)[0] == 0
        image_ok = docker_ok and run_capture(["docker.exe", "image", "inspect", "ssisls"], 20)[0] == 0
        viz_ok = docker_ok and run_capture(["docker.exe", "image", "inspect", "facts-viz"], 20)[0] == 0
        script_ok = (self.root / "setup_facts.sh").is_file() and (self.root / "run_facts_slr.sh").is_file()
        return [
            ("Windows application", True, "Native bundled interface"),
            ("Docker Desktop", docker_ok, docker_detail),
            ("Ubuntu WSL2", ubuntu_ok, "Installed" if ubuntu_ok else "Installed from this tab"),
            ("Ubuntu tools", tools_ok, "Python/Tk/Git/wget"),
            ("FACTS repository", repo_ok, repo),
            ("FACTS Docker image", image_ok, "ssisls"),
            ("Dashboard image", viz_ok and script_ok, "facts-viz and package launchers"),
        ]

    def check_system(self) -> None:
        rows = self.status_rows()
        for row, (name, ready, detail) in enumerate(rows):
            for column, value in enumerate((name, "Ready" if ready else "Missing", detail)):
                item = QTableWidgetItem(str(value))
                item.setForeground(Qt.GlobalColor.darkGreen if ready else Qt.GlobalColor.darkRed)
                self.checks.setItem(row, column, item)
        ready_count = sum(ready for _name, ready, _detail in rows)
        self.status.setText(f"System check: {ready_count}/{len(rows)} components ready")

    def install_facts(self) -> None:
        include_full_data = self.full_data.isChecked()
        rebuild_images = self.rebuild.isChecked()
        if QMessageBox.question(
            self, "Install or repair FACTS",
            "Install missing WSL/Ubuntu tools, FACTS repositories, data, and Docker images?\n\n"
            + ("Full local module data is selected (large resumable download, about 60 GB)."
               if include_full_data else "Full local module data is not selected."),
        ) != QMessageBox.StandardButton.Yes:
            return
        self.setup_log.clear()

        def task(log: Callable[[str], None], cancelled: Callable[[], bool]) -> None:
            docker_ok, detail = docker_ready()
            if not docker_ok:
                raise RuntimeError("Start Docker Desktop, then select Install again. " + detail)
            if not ubuntu_available():
                log("Installing Ubuntu WSL2. Accept the Windows administrator prompt.\n")
                ps = "$p=Start-Process -FilePath wsl.exe -ArgumentList @('--install','--distribution','Ubuntu','--no-launch') -Verb RunAs -Wait -PassThru; exit $p.ExitCode"
                code = subprocess.call(["powershell.exe", "-NoLogo", "-NoProfile", "-Command", ps])
                if code != 0 or not ubuntu_available():
                    raise RuntimeError("Ubuntu installation needs a Windows restart. Restart, then reopen this application.")
            log("Installing Ubuntu-side prerequisites…\n")
            apt = "export DEBIAN_FRONTEND=noninteractive; apt-get update && apt-get install -y python3 python3-tk git wget curl ca-certificates"
            worker = self.worker
            if worker is None or worker.stream(
                ["wsl.exe", "-d", "Ubuntu", "-u", "root", "--", "bash", "-lc", apt]) != 0:
                raise RuntimeError("Ubuntu prerequisite installation failed.")
            args = ["wsl.exe", "-d", "Ubuntu", "--cd", str(self.root), "--",
                    "bash", "setup_facts.sh"]
            if include_full_data: args.append("--with-data")
            if rebuild_images: args.append("--rebuild")
            if worker is None or worker.stream(args, self.root) != 0:
                raise RuntimeError("FACTS setup failed. Review the Setup console above.")

        self.start_task(task, self.append_setup, "Installing FACTS…")

