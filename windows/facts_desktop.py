    def run_projection(self) -> None:
        rows = self.valid_location_rows()
        workflows = self.selected_workflows()
        output = Path(self.output_dir.text().strip())
        if not workflows:
            QMessageBox.warning(self, "No workflows", "Select at least one FACTS workflow.")
            return
        if self.scale.currentIndex() == 0 and not rows:
            QMessageBox.warning(self, "No locations", "Choose a valid tab-separated location list.")
            return
        try: output.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            QMessageBox.warning(self, "Output directory", str(exc)); return
        scenario = self.scenario.currentText()
        local_run = self.scale.currentIndex() == 0
        run_stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        run_root = output / "FACTS_runs" / f"{scenario}_{run_stamp}"
        result_dir = run_root / scenario
        if QMessageBox.question(
            self, "Run FACTS",
            f"Scenario: {scenario}\nScale: {self.scale.currentText()}\n"
            f"Locations: {len(rows) if local_run else 'not used for global mean'}\n"
            f"Workflows: {', '.join(workflows)}\nSamples: {self.nsamps.value():,}\n"
            f"Output: {result_dir}\n\nStart the projection?",
        ) != QMessageBox.StandardButton.Yes:
            return
        self.settings.setValue("output", str(output))
        self.settings.setValue(f"latest_result_dir/{scenario}", str(result_dir))
        runtime = self.root / ".runtime" / scenario
        runtime.mkdir(parents=True, exist_ok=True)
        config_path = runtime / "config.yml"
        locations_path = runtime / "location.lst"
        config_path.write_text(self.current_config(), encoding="utf-8", newline="\n")
        if local_run:
            locations_path.write_text("\n".join(rows) + "\n", encoding="utf-8", newline="\n")
        self.run_log.clear(); self.progress.setValue(0)
        cpu_count = self.cpu.value()
        memory_limit = self.memory.text().strip()

        def task(log: Callable[[str], None], cancelled: Callable[[], bool]) -> None:
            if not ubuntu_available(): raise RuntimeError("Complete FACTS Setup first: Ubuntu is missing.")
            home = wsl_home(); repo = home + "/facts_ssisls/facts"
            exp = repo + "/experiments_ssisls/" + scenario
            config_wsl = wsl_path(config_path)
            run_root.mkdir(parents=True, exist_ok=True)
            output_wsl = wsl_path(run_root)
            prep = (f"test -d {shlex.quote(exp)} && "
                    f"cp {shlex.quote(config_wsl)} {shlex.quote(exp + '/config.yml')}")
            if local_run:
                locations_wsl = wsl_path(locations_path)
                prep += (f" && cp {shlex.quote(locations_wsl)} "
                         f"{shlex.quote(exp + '/location.lst')}")
            code, detail = run_capture(["wsl.exe", "-d", "Ubuntu", "--", "bash", "-lc", prep], 30)
            if code != 0: raise RuntimeError("Could not install the experiment files: " + detail)
            log("Selected workflows: " + ", ".join(workflows) + "\n")
            log("Isolated result folder: " + str(result_dir) + "\n")
            worker = self.worker
            command = ["wsl.exe", "-d", "Ubuntu", "--cd", str(self.root), "--", "env",
                       "FACTS_REPO=" + repo, "OUTPUT_ROOT=" + output_wsl,
                       "CPU_COUNT=" + str(cpu_count), "MEMORY_LIMIT=" + memory_limit,
                       "bash", "run_facts_slr.sh", scenario]
            if worker is None or worker.stream(command, self.root) != 0:
                raise RuntimeError("FACTS run failed. Review the execution console.")

        self.tabs.setCurrentIndex(1)
        self.start_task(task, self.append_run, "Running " + scenario + "…")

    def generate_dashboard(self) -> None:
        scenario = self.scenario.currentText()
        output_root = Path(self.output_dir.text().strip())
        saved_result = self.settings.value(f"latest_result_dir/{scenario}", "")
        scenario_dir = (Path(str(saved_result)) if saved_result
                        else output_root / scenario)
        netcdf_files = list(scenario_dir.glob("*.nc")) if scenario_dir.is_dir() else []
        if not netcdf_files:
            QMessageBox.warning(
                self, "No FACTS results",
                f"No NetCDF output files were found in:\n{scenario_dir}\n\n"
                "Complete a projection first or choose its output directory.")
            return
        html_path = scenario_dir / f"facts_dashboard_{scenario}.html"
        selected_location_path = self.root / ".runtime" / scenario / "location.lst"
        location_path = (selected_location_path if selected_location_path.is_file()
                         else Path(self.locations.text().strip()))
        if QMessageBox.question(
            self, "Generate results dashboard",
            f"Create a self-contained interactive HTML dashboard from "
            f"{len(netcdf_files)} NetCDF file(s)?\n\nOutput: {html_path}",
        ) != QMessageBox.StandardButton.Yes:
            return
        self.run_log.clear()
        self.settings.setValue("latest_dashboard", str(html_path))

        def task(log: Callable[[str], None], cancelled: Callable[[], bool]) -> None:
            if not ubuntu_available():
                raise RuntimeError("Complete FACTS Setup first: Ubuntu is missing.")
            home = wsl_home()
            dashboard_repo = home + "/facts_ssisls/facts.plotting.dashboard"
            scenario_wsl = wsl_path(scenario_dir)
            html_wsl = wsl_path(html_path)
            command = (f"cd {shlex.quote(dashboard_repo)} && "
                       f"bash docker/run.sh --ssp-dir {shlex.quote(scenario_wsl)} "
                       f"--output {shlex.quote(html_wsl)} "
                       f"--title {shlex.quote('FACTS ' + scenario + ' projections')}")
            if location_path.is_file():
                command += " --location-lst " + shlex.quote(wsl_path(location_path))
            worker = self.worker
            if worker is None or worker.stream(
                ["wsl.exe", "-d", "Ubuntu", "--", "bash", "-lc", command]) != 0:
                raise RuntimeError("HTML dashboard generation failed. Review the console.")
            log(f"\nDashboard created: {html_path}\n")

        self.start_task(task, self.append_run, "Generating HTML dashboard…")

