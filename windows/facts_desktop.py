def package_root() -> Path:
    if getattr(sys, "frozen", False):
        executable_dir = Path(sys.executable).resolve().parent
        backend_dir = executable_dir / "_FACTS_backend"
        return backend_dir if backend_dir.is_dir() else executable_dir
    return Path(__file__).resolve().parent.parent


def run_capture(command: list[str], timeout: int = 30) -> tuple[int, str]:
    try:
        result = subprocess.run(command, capture_output=True, text=True,
                                encoding="utf-8", errors="replace", timeout=timeout)
        return result.returncode, (result.stdout + result.stderr).replace("\x00", "").strip()
    except (OSError, subprocess.SubprocessError) as exc:
        return 127, str(exc)


def ubuntu_available() -> bool:
    code, output = run_capture(["wsl.exe", "--list", "--quiet"], 20)
    return code == 0 and any(line.strip().lower() == "ubuntu"
                             for line in output.splitlines())


def wsl_home() -> str:
    code, output = run_capture(
        ["wsl.exe", "-d", "Ubuntu", "--", "bash", "-lc", "printf %s \"$HOME\""], 20)
    if code != 0 or not output.startswith("/"):
        raise RuntimeError("Could not determine the Ubuntu home directory: " + output)
    return output.splitlines()[0].strip()


def wsl_path(path: Path) -> str:
    code, output = run_capture(
        ["wsl.exe", "-d", "Ubuntu", "--", "wslpath", "-a", "-u", str(path)], 20)
    if code != 0 or not output:
        raise RuntimeError("Could not translate Windows path for WSL: " + str(path))
    return output.splitlines()[0].strip()


def docker_ready() -> tuple[bool, str]:
    code, output = run_capture(["docker.exe", "info"], 25)
    if code == 0:
        vcode, version = run_capture(
            ["docker.exe", "version", "--format", "{{.Server.Version}}"], 15)
        return True, "Engine " + (version if vcode == 0 else "running")
    return False, output.splitlines()[-1] if output else "Docker Desktop is not running"


def build_config(scenario: str, local: bool, workflows: list[str], use_vlm: bool,
                 use_esl: bool, esl_years: str, nsamps: int, baseyear: int,
                 pstart: int, pend: int, pstep: int) -> str:
    lines: list[str] = []
    add = lines.append
    lws_scenario = {
        "ssp119": "ssp1", "ssp126": "ssp1", "ssp245": "ssp2",
        "ssp370": "ssp3", "ssp585": "ssp5",
    }[scenario]
    add(f"# Generated by FACTS Projection Studio: {'LOCAL' if local else 'GLOBAL'} run")
    add(f"# {datetime.now():%Y-%m-%d %H:%M:%S}")
    add("")
    add("global-options:")
    add(f"    nsamps: {nsamps}")
    add(f"    scenario: {scenario}")
    add(f"    pyear_start: {pstart}")
    add(f"    pyear_end: {pend}")
    add(f"    pyear_step: {pstep}")
    add(f"    baseyear: {baseyear}")
    add(f'    pipeline_file: "{"pipeline.yml" if local else "pipeline.global.yml"}"')
    add("")
    add("climate_step:")
    add("    temperature:")
    add('        module_set: "fair"')
    add('        module: "temperature"')
    add("        generates_climate_output: true")
    add("")
    add("sealevel_step:")
    for key, module_set, module, module_wfs, options, flag in MODULES:
        if flag == "vlm" and (not use_vlm or not local):
            continue
        kept = [wf for wf in module_wfs if wf in workflows]
        if not kept:
            continue
        add(f"    {key}:")
        add(f'        module_set: "{module_set}"')
        add(f'        module: "{module}"')
        if flag == "ais":
            add(f'        pipeline_file: "{"pipeline.AIS.yml" if local else "pipeline.AIS.global.yml"}"')
        chosen_options = options
        if flag == "lws":
            chosen_options = (("scenario", f'"{lws_scenario}"'), ("dcrate_lo", "-0.4"))
        if chosen_options:
            add("        options:")
            for name, value in chosen_options:
                add(f"            {name}: {value}")
        add("        include_in_workflow:")
        for wf in kept:
            add(f'            - "{wf}"')
        add("")
    add("totaling_step:")
    add("    total:")
    add('        module_set: "facts"')
    add('        module: "total"')
    add("        loop_over_workflows: true")
    add("        loop_over_scales: true")
    add("        stages:")
    add("            - workflow")
    if use_esl and local:
        add("")
        add("esl_step:")
        add("    extremesealevel:")
        add("        loop_over_workflows: true")
        add('        module_set: "extremesealevel"')
        add('        module: "pointsoverthreshold"')
        add("        options:")
        add(f"            target_years: {esl_years or '2050,2100'}")
        add('            total_localsl_file: "$SHARED/totaled/%EXPERIMENT_NAME%.total.workflow.%WORKFLOW_NAME%.local.nc"')
    return "\n".join(lines) + "\n"


class TaskWorker(QThread):
    output = Signal(str)
    completed = Signal(int, str)

    def __init__(self, task: Callable[[Callable[[str], None], Callable[[], bool]], None]):
        super().__init__()
        self.task = task
        self.process: subprocess.Popen[str] | None = None

    def stream(self, command: list[str], cwd: Path | None = None) -> int:
        self.output.emit("$ " + subprocess.list2cmdline(command) + "\n")
        self.process = subprocess.Popen(
            command, cwd=str(cwd) if cwd else None, stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace",
            bufsize=1)
        assert self.process.stdout is not None
        for line in self.process.stdout:
            self.output.emit(line)
            if self.isInterruptionRequested():
                self.process.terminate()
                break
        return self.process.wait()

    def run(self) -> None:
        try:
            self.task(self.output.emit, self.isInterruptionRequested)
            self.completed.emit(0, "Completed successfully")
        except Exception as exc:  # GUI boundary: show actionable error
            self.output.emit("\nERROR: " + str(exc) + "\n")
            self.completed.emit(1, str(exc))

    def cancel(self) -> None:
        self.requestInterruption()
        if self.process is not None and self.process.poll() is None:
            self.process.terminate()


